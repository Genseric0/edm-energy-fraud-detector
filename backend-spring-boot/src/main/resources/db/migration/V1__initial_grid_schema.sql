-- Esquema actual do protótipo: preserva tipos e nomes usados pelas entidades.
-- Não alterar depois de aplicado; evoluir apenas através de novas migrações.
CREATE TABLE transformers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(255) NOT NULL UNIQUE,
    neighborhood VARCHAR(255) NOT NULL,
    capacity_kva DOUBLE PRECISION,
    total_supplied_kwh DOUBLE PRECISION NOT NULL
);
CREATE TABLE residential_meters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meter_number VARCHAR(255) NOT NULL UNIQUE,
    resident_name VARCHAR(255) NOT NULL,
    phone_number VARCHAR(255),
    address VARCHAR(255) NOT NULL,
    billed_kwh DOUBLE PRECISION NOT NULL,
    installation_location VARCHAR(255) NOT NULL,
    remote_reading_enabled BOOLEAN NOT NULL,
    transformer_id BIGINT NOT NULL REFERENCES transformers(id)
);
CREATE TABLE meter_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meter_id BIGINT NOT NULL REFERENCES residential_meters(id),
    recorded_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    energy_kwh DOUBLE PRECISION NOT NULL,
    source VARCHAR(255) NOT NULL
);
CREATE TABLE inspection_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meter_id BIGINT NOT NULL REFERENCES residential_meters(id),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    reported_by VARCHAR(255) NOT NULL,
    estimated_unaccounted_kwh DOUBLE PRECISION NOT NULL,
    inspection_notes VARCHAR(4000),
    status VARCHAR(255) NOT NULL
);
