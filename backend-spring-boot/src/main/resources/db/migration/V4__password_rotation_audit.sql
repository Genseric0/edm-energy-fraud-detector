CREATE TABLE account_security_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES app_user(id),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    action VARCHAR(32) NOT NULL CHECK (action = 'PASSWORD_CHANGED'),
    auth_version BIGINT NOT NULL CHECK (auth_version > 0),
    UNIQUE (account_id, auth_version)
);
CREATE INDEX idx_account_security_event_time ON account_security_event(account_id, occurred_at);

-- Protege contra UPDATE/DELETE acidental pela aplicação. O proprietário da BD
-- continua privilegiado; isto não substitui segregação de credenciais/backups.
CREATE FUNCTION reject_account_security_event_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Account security events are append-only';
END;
$$;
CREATE TRIGGER account_security_event_append_only
BEFORE UPDATE OR DELETE ON account_security_event
FOR EACH ROW EXECUTE FUNCTION reject_account_security_event_mutation();
